def page(fname, title, active, body, extra=""):
    nav = "".join('<a href="%s"%s>%s</a>' % (href,
           ' class="active"' if i == active else "", label)
           for href, label, i in NAV)
    out = (SHELL.replace("@@TITLE@@", title).replace("@@NAV@@", nav)
               .replace("@@BODY@@", body).replace("@@EXTRA@@", extra))
    open(os.path.join(OUT, fname), "w", encoding="utf-8").write(out)
    print("wrote", fname)


def pre(code):
    return "<pre><code>" + html.escape(code.strip("\n")) + "</code></pre>"


